// Draw a single character in an 8x8 cell
export function drawChar(ctx, ch, x, y, color = '#FCFCFC') {
  const glyph = FONT_GLYPHS[ch.toUpperCase()] || FONT_GLYPHS['?'];
  ctx.fillStyle = color;
  const startX = Math.floor(x);
  const startY = Math.floor(y);

  for (let r = 0; r < glyph.length; r++) {
    const row = glyph[r];
    for (let c = 0; c < row.length; c++) {
      if (row[c] === '#' || row[c] === 'c') {
        ctx.fillRect(startX + c + 1, startY + r, 1, 1);
      }
    }
  }
}

// Draw string of text with 8px character spacing
export function drawText(ctx, text, x, y, color = '#FCFCFC') {
  const str = String(text);
  let curX = Math.floor(x);
  const curY = Math.floor(y);

  for (let i = 0; i < str.length; i++) {
    const ch = str[i];
    drawChar(ctx, ch, curX, curY, color);
    curX += 8;
  }
}
